import { useEffect, useRef, useState } from "react";
import type { FormEvent } from "react";
import { api, newConfig } from "./api";
import type { Config, Health, Project } from "./api";

const stages = ["Capture", "Design intelligence", "Reference kit", "Visual comparison", "Publish"];
type Screen = "dashboard" | "projects" | "new";
function message(error: unknown) { return error instanceof Error ? error.message : String(error); }

export default function App() {
  const [screen, setScreen] = useState<Screen>("dashboard");
  const [health, setHealth] = useState<Health | null>(null);
  const [items, setItems] = useState<Project[]>([]);
  const [offset, setOffset] = useState(0);
  const [selected, setSelected] = useState<Project | null>(null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(true);
  const [detailLoading, setDetailLoading] = useState(false);
  const [busy, setBusy] = useState(false);
  const [notice, setNotice] = useState("");
  const [name, setName] = useState("");
  const [url, setUrl] = useState("");
  const [backend, setBackend] = useState("Django");
  const [frontend, setFrontend] = useState("React / TypeScript");
  const [imported, setImported] = useState<Config | null>(null);
  const requestId = useRef(0);
  const detailId = useRef(0);
  const submitLock = useRef(false);

  async function refresh(page = 0) {
    const id = ++requestId.current;
    setLoading(true); setError("");
    const results = await Promise.allSettled([api.health(), api.list(page)]);
    if (id !== requestId.current) return;
    setHealth(results[0].status === "fulfilled" ? results[0].value : null);
    if (results[1].status === "fulfilled") {
      setItems(results[1].value.items); setOffset(page);
    } else { setError(message(results[1].reason)); }
    setLoading(false);
  }
  useEffect(() => { void refresh(); return () => { requestId.current++; detailId.current++; }; }, []);
  function navigate(next: Screen) {
    detailId.current++; setDetailLoading(false); setSelected(null); setScreen(next); setError(""); setNotice("");
  }
  async function openProject(id: string) {
    const seq = ++detailId.current;
    setScreen("projects"); setSelected(null); setDetailLoading(true); setError("");
    try { const project = await api.get(id); if (seq === detailId.current) setSelected(project); }
    catch (e) { if (seq === detailId.current) setError(message(e)); }
    finally { if (seq === detailId.current) setDetailLoading(false); }
  }
  const config = imported ?? newConfig(name, url, backend, frontend);
  async function submit(event: FormEvent<HTMLFormElement>, create: boolean) {
    event.preventDefault();
    if (submitLock.current) return;
    submitLock.current = true; setBusy(true); setError(""); setNotice("");
    try {
      await api.validate(config);
      if (create) {
        const project = await api.create(config);
        navigate("projects"); setSelected(project); setImported(null); setName(""); setUrl("");
        await refresh();
        setNotice("Project created. Documentation generated by the server.");
      } else { setNotice("Configuration is valid."); }
    } catch (e) { setError(message(e)); }
    finally { submitLock.current = false; setBusy(false); }
  }
  async function importFile(file: File | undefined) {
    if (!file) return;
    setError(""); setNotice("");
    try {
      if (file.size > 1024 * 1024) throw new Error("Configuration exceeds 1 MB.");
      const data: unknown = JSON.parse(await file.text());
      if (!data || typeof data !== "object" || Array.isArray(data)) throw new Error("Expected a JSON object.");
      await api.validate(data as Config);
      setImported(data as Config); setNotice("Imported configuration is valid.");
    } catch (e) { setError(message(e)); }
  }

  return <div className="shell">
    <aside className="sidebar">
      <div className="brand"><span className="logo">ST</span><div>Site Transfer<small>STUDIO / LOCAL</small></div></div>
      <div className="nav-label">WORKSPACE</div>
      <nav aria-label="Workspace">
        {([["dashboard","Dashboard"],["projects","Projects"],["new","New transfer"]] as const).map(([key,label]) =>
          <button key={key} disabled={busy} className={screen === key ? "nav active" : "nav"} onClick={() => navigate(key)}>{label}</button>)}
      </nav>
      <div className="nav-label">PIPELINE / UPCOMING</div>
      {stages.map(stage => <div className="future" key={stage}>{stage}</div>)}
      <div className="sidebar-bottom"><span className={health?.status === "ready" ? "dot green" : "dot"} />{health?.status === "ready" ? "Local runtime ready" : "Runtime not confirmed"}<small>PR-03 · GUI foundation</small></div>
    </aside>
    <main>
      <header><div><div className="eyebrow">WORKSPACE / {screen.toUpperCase()}</div><h1>{screen === "dashboard" ? "Overview" : screen === "new" ? "New transfer" : selected ? selected.config.target.project_name : "Projects"}</h1></div>
        <button className="secondary" disabled={loading || busy} onClick={() => void refresh(offset)}>Refresh</button>
      </header>
      {error && <div className="alert error" role="alert">{error}</div>}
      {notice && <div className="alert success" role="status">{notice}</div>}
      {screen === "dashboard" && <>
        <section className="hero"><div className="eyebrow">REFERENCE-DRIVEN DEVELOPMENT</div><h2>From reference to implementation.</h2><p>Organize website transfer projects and prepare evidence for coding agents. Browser capture arrives in PR-04.</p><button className="primary" onClick={() => navigate("new")}>New transfer +</button></section>
        <div className="metrics">
          <div className="panel"><div className="eyebrow">API / DATABASE / REDIS</div><h2>{health?.status ?? "Unknown"}</h2>{health?.checks && Object.entries(health.checks).map(([key,ok]) => <div key={key}>{key}: {ok ? "Ready" : "Unavailable"}</div>)}</div>
          <div className="panel"><div className="eyebrow">PROJECTS ON THIS PAGE</div><h2>{loading ? "…" : items.length}</h2><p>Persistent project registry</p></div>
          <div className="panel"><div className="eyebrow">CAPTURE ENGINE</div><h2>Pending</h2><p>No browser jobs are executed yet.</p></div>
        </div>
      </>}
      {(screen === "dashboard" || screen === "projects") && !selected && <>
        <section className="panel"><div className="section-head"><h2>Projects</h2><button className="secondary" onClick={() => navigate("new")}>Create project</button></div>
          {detailLoading ? <p>Loading project…</p> : loading ? <p>Loading projects…</p> : items.length === 0 ? <p>No projects on this page.</p> :
            <div className="project-list">{items.map(project => <button className="project-row" key={project.id} onClick={() => void openProject(project.id)}><span><strong>{project.config.target.project_name}</strong><small>{project.config.source.url}</small></span><span className="tag">Scaffold</span></button>)}</div>}
          <div className="pagination"><button className="secondary" disabled={loading || offset === 0} onClick={() => void refresh(Math.max(0,offset-50))}>Previous</button><span>Page {Math.floor(offset/50)+1}</span><button className="secondary" disabled={loading || items.length < 50} onClick={() => void refresh(offset+50)}>Next</button></div>
        </section>
      </>}
      {screen === "projects" && selected && <section className="panel">
        <button className="secondary" onClick={() => navigate("projects")}>Back to projects</button>
        <h2>{selected.config.target.project_name}</h2>
        <dl><dt>Reference</dt><dd>{selected.config.source.url}</dd><dt>Backend</dt><dd>{selected.config.target.backend ?? "Not specified"}</dd><dt>Frontend</dt><dd>{selected.config.target.frontend ?? "Not specified"}</dd><dt>Project ID</dt><dd>{selected.id}</dd><dt>Created</dt><dd>{new Date(selected.created_at).toLocaleString()}</dd></dl>
        <h3>Generated project documents</h3><p>CONTEXT.md · AGENTS.md · TASK.md · README.md</p>
        <h3>Configuration</h3><pre>{JSON.stringify(selected.config,null,2)}</pre>
        <p className="muted">Capture, comparison and publication are not available in this stage.</p>
      </section>}
      {screen === "new" && <section className="panel form-panel">
        <h2>Project configuration</h2><p>Enter reference and target details or import an existing JSON config.</p>
        <label className="file-label">Import JSON<input type="file" accept=".json,application/json" disabled={busy} onChange={e => { void importFile(e.target.files?.[0]); e.target.value = ""; }} /></label>
        <form onSubmit={e => void submit(e, true)}>
          {imported ? <><pre>{JSON.stringify(imported,null,2)}</pre><button type="button" className="secondary" disabled={busy} onClick={() => {setImported(null);setNotice("");}}>Use manual form</button></> :
          <fieldset disabled={busy}><label>Project name<input required pattern="[A-Za-z0-9][A-Za-z0-9_-]{0,63}" value={name} onChange={e => {setName(e.target.value);setNotice("");}} placeholder="my_project" /></label>
            <label>Reference URL<input required type="url" value={url} onChange={e => {setUrl(e.target.value);setNotice("");}} placeholder="https://example.com" /></label>
            <div className="form-grid"><label>Backend<input required value={backend} onChange={e => {setBackend(e.target.value);setNotice("");}} maxLength={80}/></label><label>Frontend<input required value={frontend} onChange={e => {setFrontend(e.target.value);setNotice("");}} maxLength={80}/></label></div>
            <div className="settings">Desktop 1440 × 900 · Mobile 390 × 844 · Max 30 pages<br/>CONTEXT.md and AGENTS.md are mandatory.</div>
          </fieldset>}
          <div className="actions"><button type="button" className="secondary" disabled={busy} onClick={e => { if(e.currentTarget.form?.reportValidity()) void submit(e as unknown as FormEvent<HTMLFormElement>,false); }}>Validate configuration</button><button className="primary" type="submit" disabled={busy}>{busy ? "Working…" : "Create project"}</button></div>
        </form>
        <p className="muted">This creates a documentation scaffold only; it does not visit the reference site.</p>
      </section>}
      <footer>Site Transfer Studio · Local workspace · Capture not implemented in PR-03</footer>
    </main>
  </div>;
}
